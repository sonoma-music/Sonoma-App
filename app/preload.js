const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('sonoma', {
  getStore: () => ipcRenderer.invoke('store:get'),
  setStore: data => ipcRenderer.invoke('store:set', data),
  pickLibrary: () => ipcRenderer.invoke('library:pick'),
  onLibraryProgress: cb => ipcRenderer.on('library:progress', (_e, p) => cb(p)),
  localLyrics: file => ipcRenderer.invoke('lyrics:local', file),
  importM3U: () => ipcRenderer.invoke('import:m3u'),
  importSpotify: opts => ipcRenderer.invoke('import:spotify', opts),
  winMin: () => ipcRenderer.invoke('win:min'),
  winMax: () => ipcRenderer.invoke('win:max'),
  winClose: () => ipcRenderer.invoke('win:close'),
  copy: text => ipcRenderer.invoke('clipboard:write', text),
  openExternal: url => ipcRenderer.invoke('open-external', url),
  onOpenLink: cb => ipcRenderer.on('open-link', (_e, url) => cb(url)),
  resolveLink: url => ipcRenderer.invoke('get:resolve', url),
  buyLinks: q => ipcRenderer.invoke('get:buyLinks', q),
  providers: () => ipcRenderer.invoke('get:providers'),
  searchSources: q => ipcRenderer.invoke('get:search', q),
  sourceTracks: q => ipcRenderer.invoke('get:tracks', q),
  findFree: q => ipcRenderer.invoke('get:findFree', q),
  dlAdd: tracks => ipcRenderer.invoke('dl:add', tracks),
  dlList: () => ipcRenderer.invoke('dl:list'),
  dlCancel: id => ipcRenderer.invoke('dl:cancel', id),
  dlRetry: id => ipcRenderer.invoke('dl:retry', id),
  dlClear: () => ipcRenderer.invoke('dl:clear'),
  onDl: cb => ipcRenderer.on('dl:update', (_e, j) => cb(j)),
  onAdded: cb => ipcRenderer.on('library:added', (_e, t) => cb(t)),
  metaLookup: base => ipcRenderer.invoke('meta:lookup', base),
  metaApply: q => ipcRenderer.invoke('meta:apply', q),
  cdInfo: () => ipcRenderer.invoke('cd:info'),
  cdRip: info => ipcRenderer.invoke('cd:rip', info),
  onCd: cb => ipcRenderer.on('cd:progress', (_e, p) => cb(p)),
  setWatch: dirs => ipcRenderer.invoke('watch:set', dirs),
  pickFolder: () => ipcRenderer.invoke('dialog:folder'),
  openPath: p => ipcRenderer.invoke('shell:open', p),
  mediaUrl: file => 'sonoma-media://local/?p=' + encodeURIComponent(file)
});
